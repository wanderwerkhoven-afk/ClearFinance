"""One-command reproducible proof-of-concept: input → layers → injected fault → report.

The first demo uses an EXTRACTIVE merger. It never pretends that its output
is generated by a language model or that lexical metrics validate semantics.
"""
from __future__ import annotations
import argparse,copy,html,json
from pathlib import Path
from .input import load_document
from .pipeline import ExtractiveMerger, OllamaMerger, run
from .metrics import evaluate,rouge_n,rouge_l
from .eda import describe

def inject_known_fault(result:dict,old="120",new="125") -> tuple[dict,dict]:
    """Modify exactly one claim AFTER a merge; no source or earlier layers changed."""
    altered=copy.deepcopy(result)
    for layer in altered["layers"][1:]:
        for claim in layer["claims"]:
            import re
            pat=r"(?<!\w)"+re.escape(old)+r"(?!\w)"
            if re.search(pat,claim["text"]):
                before=claim["text"]
                claim["text"]=re.sub(pat,new,before,count=1)
                return altered,{"layer":layer["level"],"claim_id":claim["id"],
                                "original":before,"mutated":claim["text"],
                                "kind":"wrong_number","expected":"numeric_review",
                                "note":"Only the selected layer was altered. Subsequent layers are unchanged; no propagation is claimed."}
    raise ValueError("No injectable claim at a merge layer; use a fixture containing 120 in a retained claim")

def build_demo(source_path:str,mode="extractive",model="qwen2.5:7b",fan_in=3,old="120",new="125"):
    source=load_document(source_path)
    merger=ExtractiveMerger() if mode=="extractive" else OllamaMerger(model=model)
    baseline=run(source,merger,fan_in=fan_in)
    changed,fault=inject_known_fault(baseline,old,new)
    before=evaluate(baseline)
    after=evaluate(changed)
    def claim_check(metrics,layer_id,claim_id):
        layer=next(x for x in metrics["levels"] if x["level"]==layer_id)
        return next(x for x in layer["checks"] if x["claim_id"]==claim_id)
    original_check=claim_check(before,fault["layer"],fault["claim_id"])
    changed_check=claim_check(after,fault["layer"],fault["claim_id"])
    return {
        "document":{"input":str(source_path),"eda":describe(source)},
        "baseline":baseline,"baseline_evaluation":before,
        "fault_injection":fault,"injected":changed,"injected_evaluation":after,
        "comparison":{
            "numeric_before":original_check["numeric"]["status"],
            "numeric_after":changed_check["numeric"]["status"],
            "source_pages":changed_check["source_pages"],
            "rouge1":round(rouge_n(fault["original"],fault["mutated"],1),4),
            "rouge2":round(rouge_n(fault["original"],fault["mutated"],2),4),
            "rougeL":round(rouge_l(fault["original"],fault["mutated"]),4),
        },
        "disclaimer":"Synthetic injected error; not a validated semantic metric or end-to-end LLM result."
    }


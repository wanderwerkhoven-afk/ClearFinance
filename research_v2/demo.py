def render_html(result:dict) -> str:
    escape=html.escape
    def txt(v):return escape(str(v))
    fault=result["fault_injection"]
    compare=result["comparison"]
    source={b["id"]:b for b in result["baseline"]["source"]}
    layers=result["injected"]["layers"]
    cards=[]
    for layer in layers:
        details=[]
        eval_layer=next(x for x in result["injected_evaluation"]["levels"] if x["level"]==layer["level"])
        checks={c["claim_id"]:c for c in eval_layer["checks"]}
        for claim in layer["claims"]:
            check=checks[claim["id"]]
            status=check["numeric"]["status"]
            mark=" <span class='pill error'>Numerieke afwijking: controleer</span>" if status=="review" else ""
            origin=", ".join(claim["origin_ids"]) or "bronextractie"
            cited="; ".join(f"p.{source[s]['page']}: {source[s]['text'][:180]}" for s in claim["source_ids"] if s in source)
            details.append(f"<div class='claim'><b>{txt(claim['id'])}</b>{mark}<p>{txt(claim['text'])}</p><small>Vorige laag: {txt(origin)}<br>Originele bron: {txt(cited)}</small></div>")
        cards.append(f"<section class='card'><h2>Laag {layer['level']} · {len(layer['claims'])} claims</h2>{''.join(details)}</section>")
    summary=(f"<div class='grid'><article class='card good'><h2>Vóór foutinjectie</h2>"
             f"<p>Cijfercheck: <b>{txt(compare['numeric_before'])}</b></p></article>"
             f"<article class='card bad'><h2>Na foutinjectie</h2><p>Cijfercheck: "
             f"<b>{txt(compare['numeric_after'])}</b> — bronpagina's {txt(compare['source_pages'])}</p></article></div>")
    return (f"<!doctype html><html lang='nl'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>ClearFinance · Evaluatie per laag</title><style>{CSS}</style></head><body>"
            f"<header><div><h1>ClearFinance · Laagevaluatie</h1><p>Hierarchical merging als testinstrument · "
            f"de evaluatiemodule is het product</p></div></header><main>"
            f"<p class='muted'>Methode: {txt(result['baseline']['run']['method'])}. "
            f"Deze demonstratie is synthetisch en wordt lokaal gegenereerd zonder externe API.</p>"
            f"<section class='card'><h2>Geïnjecteerde fout</h2><p>{txt(fault['original'])} → "
            f"<b>{txt(fault['mutated'])}</b></p><p>Laag {fault['layer']}, claim {txt(fault['claim_id'])}</p>"
            f"<p>ROUGE-1: {compare['rouge1']:.3f} · ROUGE-2: {compare['rouge2']:.3f} · "
            f"ROUGE-L: {compare['rougeL']:.3f}</p></section>"
            f"{summary}<h2>Alle tussenlagen en bronbewijs</h2>{''.join(cards)}"
            f"<p class='muted'>Let op: bron-ID-validiteit is geen semantische faithfulness. "
            f"Globale/lokale NLI en drift zijn nog niet gevalideerd. "
            f"De fout is geïnjecteerd in één laag; propagatie naar latere lagen is niet gesimuleerd.</p>"
            f"</main></body></html>")

def main():
    p=argparse.ArgumentParser(description="Offline Case B end-to-end evaluation demo")
    p.add_argument("--input",default="research_v2/fixtures/synthetic_report.json")
    p.add_argument("--out",default="research_v2/output/demo")
    p.add_argument("--mode",choices=["extractive","ollama"],default="extractive")
    p.add_argument("--model",default="qwen2.5:7b")
    p.add_argument("--old",default="120")
    p.add_argument("--new",default="125")
    args=p.parse_args()
    out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    result=build_demo(args.input,args.mode,args.model,old=args.old,new=args.new)
    (out/"run.json").write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding="utf-8")
    (out/"index.html").write_text(render_html(result),encoding="utf-8")
    print(json.dumps({"html":str(out/"index.html"),"json":str(out/"run.json"),
                      "layers":len(result["injected"]["layers"]),"comparison":result["comparison"]},ensure_ascii=False))
if __name__=="__main__":main()
